#!/usr/bin/env python3
"""Freeze the progress chart's purpose split into a committed file.

    python3 tools/purpose_map.py [--out FILE]   # default: generated/purpose.tsv

Uses the reference C++ decompilation (`SSX3_REF`, `tools/.refindex.json`
from `tools/refindex.py`) once, and writes address -> purpose group for every
function in `generated/functions.tsv`. `tools/progress.py` reads the map, so
the chart needs no reference checkout: same tree = same SVG, every run.
Regenerate when the reference moves (record its revision below), and keep
the refreshed `docs/images/progress.svg` the CI job commits.

Only addresses and group names are written: no code, bytes or strings.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from progress import GROUPS, classify, rust_dirs  # noqa: E402

SHORT = dict(zip(("game", "presentation", "engine"), GROUPS))


def ref_dirs():
    """Address -> top source directory of the reference (progress.py's old
    ref_dirs, inlined: the map replaces it there)."""
    import json

    from refsrc import REF, load_symbols

    index = json.load(open(os.path.join(ROOT, "tools/.refindex.json")))
    sample = next(iter(index.values()), None)
    if sample and not sample[1].startswith(os.path.join(REF, "")):
        sys.exit(
            "tools/.refindex.json is indexed from another tree; rerun "
            "tools/refindex.py with this SSX3_REF first"
        )
    symbols = load_symbols()
    out = {}
    for addr, name in symbols.items():
        entry = index.get(name)
        if entry:
            rel = os.path.relpath(entry[1], os.path.join(REF, "src"))
            out[addr] = rel.split("/")[0].removesuffix(".cpp").removesuffix(".c")
    return out


def ref_rev():
    from refsrc import REF

    try:
        return subprocess.run(
            ["git", "-C", REF, "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return "unknown"


def main(argv):
    out = os.path.join(ROOT, "generated/purpose.tsv")
    if "--out" in argv:
        out = argv[argv.index("--out") + 1]
    ref, rust = ref_dirs(), rust_dirs()
    addrs = []
    for line in open(os.path.join(ROOT, "generated/functions.tsv")):
        cols = line.rstrip("\n").split("\t")
        try:
            addrs.append((int(cols[0], 16), cols[2] if len(cols) > 2 else ""))
        except (ValueError, IndexError):
            pass
    short = {v: k for k, v in SHORT.items()}
    rows = sorted(
        (a, short[classify(name, ref.get(a), rust.get(a))]) for a, name in addrs)
    with open(out, "w") as f:
        f.write(
            "# address -> purpose group for tools/progress.py. Generated by\n"
            "# tools/purpose_map.py from https://github.com/DevvyDont/ssx3\n"
            f"# @ {ref_rev()}; regenerate when the reference moves.\n"
            "# Columns: hex start address, one of game presentation engine.\n"
        )
        for a, g in rows:
            f.write(f"{a:08x}\t{g}\n")
    print(f"{len(rows)} functions -> {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
