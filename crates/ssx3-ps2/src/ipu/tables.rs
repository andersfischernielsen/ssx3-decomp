/// A variable-length code: `code` of `length` bits decodes to `value`.
#[derive(Clone, Copy)]
pub struct Vlc {
    pub code: u16,
    pub length: u8,
    pub value: u32,
}

/// A DCT coefficient code (B.14/B.15). `run == ESCAPE` marks the escape code.
#[derive(Clone, Copy)]
pub struct Dct {
    pub code: u16,
    pub length: u8,
    pub run: u8,
    pub level: i16,
}

pub const ESCAPE: u8 = 255;

const fn v(code: u16, length: u8, value: u32) -> Vlc {
    Vlc {
        code,
        length,
        value,
    }
}

const fn d(code: u16, length: u8, run: u8, level: i16) -> Dct {
    Dct {
        code,
        length,
        run,
        level,
    }
}

