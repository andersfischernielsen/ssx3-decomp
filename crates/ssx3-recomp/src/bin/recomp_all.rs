//! Generate Rust for the **entire** function inventory, sharded into modules.
//!
//! Unlike `recomp-gen` (which emits the call closure of a start function into the
//! runtime crate), this writes every function to `generated/code/`, one module per
//! 64 KiB of address space, plus `mod.rs` and a manifest. It is intentionally not
//! compiled by default — the whole game is far too much Rust for one `rustc`
//! invocation.
//!
//! ```text
//! recomp-all [--out-dir generated/code]
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use ssx3_recomp::codegen;
use ssx3_recomp::index;
use ssx3_recomp::program::Program;

fn main() {
    let mut args = std::env::args().skip(1);
    let mut out_dir = "generated/code".to_string();
    while let Some(a) = args.next() {
        match a.as_str() {
            "--out-dir" => out_dir = args.next().expect("--out-dir PATH"),
            other => panic!("unknown argument {other}"),
        }
    }

    let program = Program::open("orig/SLUS_207.72").unwrap_or_else(|e| {
        eprintln!("could not open orig/SLUS_207.72: {e}");
        eprintln!("run tools/extract-from-iso.sh first");
        std::process::exit(1);
    });

    let funcs = index().functions();
    let translated: BTreeSet<u32> = funcs.iter().map(|f| f.address).collect();

    // Shard by 64 KiB of address space.
    let mut shards: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for f in funcs {
        shards.entry(f.address >> 16).or_default().push(f.address);
    }

    let dir = Path::new(&out_dir);
    std::fs::create_dir_all(dir).ok();

    let (mut total_funcs, mut total_insts, mut total_unsup) = (0usize, 0usize, 0usize);
    let (mut total_structured, mut total_bytes) = (0usize, 0usize);
    let mut manifest =
        String::from("# file\tfuncs\tinstructions\tunsupported\tstructured\tbytes\n");

    for (&hi, addrs) in &shards {
        let mut src = String::new();
        let _ = writeln!(
            src,
            "//! Shard {hi:#06x}: {} function(s). Auto-generated by recomp-all; do not edit.",
            addrs.len()
        );
        src.push_str(
            "#![allow(unused_variables, unused_mut, unused_assignments, clippy::all)]\n\n",
        );
        src.push_str("use crate::Cpu;\n\n");

        let (mut s_insts, mut s_unsup, mut s_struct) = (0usize, 0usize, 0usize);
        for &a in addrs {
            let f = index().by_address(a).unwrap();
            let body = codegen::emit_function_with(&program, f, &translated, "crate::code::");
            s_insts += program.decode(f).len();
            s_unsup += body.matches("unimplemented(").count();
            if !body.contains("match pc") {
                s_struct += 1;
            }
            src.push_str(&body);
            src.push('\n');
        }

        let file = format!("g{hi:04x}.rs");
        let bytes = src.len();
        std::fs::write(dir.join(&file), src).expect("write shard");

        total_funcs += addrs.len();
        total_insts += s_insts;
        total_unsup += s_unsup;
        total_structured += s_struct;
        total_bytes += bytes;
        let _ = writeln!(
            manifest,
            "{file}\t{}\t{s_insts}\t{s_unsup}\t{s_struct}\t{bytes}",
            addrs.len()
        );
    }

    let mut mod_rs = String::from(
        "//! Auto-generated by recomp-all. Do not edit.\n//!\n//! Sharded translation of the whole SSX 3 inventory.\n\n",
    );
    for &hi in shards.keys() {
        let _ = writeln!(mod_rs, "pub mod g{hi:04x};");
    }
    mod_rs.push('\n');
    for &hi in shards.keys() {
        let _ = writeln!(mod_rs, "pub use g{hi:04x}::*;");
    }
    std::fs::write(dir.join("mod.rs"), mod_rs).expect("write mod.rs");
    std::fs::write(dir.join("MANIFEST.txt"), manifest).expect("write manifest");

    println!("shards            : {}", shards.len());
    println!("functions         : {total_funcs}");
    println!("instructions      : {total_insts}");
    println!(
        "structured        : {total_structured} ({}%)",
        total_structured * 100 / total_funcs.max(1)
    );
    println!("unsupported lower : {total_unsup}");
    println!("rust bytes        : {total_bytes}");
    println!("output            : {out_dir}");
}
