//! Generate Rust source for translated functions.
//!
//! Walks the direct-call graph from a start function and emits
//! `crates/ssx3-runtime/src/generated.rs`.
//!
//! ```text
//! recomp-gen                       # from entry, depth 2, up to 256 functions
//! recomp-gen --depth 3 --limit 512
//! recomp-gen --start 0x004239a0
//! ```

use std::collections::{BTreeSet, VecDeque};
use std::path::Path;

use ssx3_recomp::codegen;
use ssx3_recomp::index;
use ssx3_recomp::program::Program;
use ssx3_recomp::r5900::Operands;

fn main() {
    let mut args = std::env::args().skip(1);
    let mut start = 0x0010_0008u32;
    let mut depth = 2u32;
    let mut limit = 256usize;
    let mut out = "crates/ssx3-runtime/src/generated.rs".to_string();

    while let Some(a) = args.next() {
        match a.as_str() {
            "--start" => {
                start = args
                    .next()
                    .and_then(|s| u32::from_str_radix(s.trim_start_matches("0x"), 16).ok())
                    .expect("--start ADDR")
            }
            "--depth" => depth = args.next().unwrap().parse().expect("--depth N"),
            "--limit" => limit = args.next().unwrap().parse().expect("--limit N"),
            "--out" => out = args.next().expect("--out PATH"),
            other => panic!("unknown argument {other}"),
        }
    }

    let program = Program::open("orig/SLUS_207.72").unwrap_or_else(|e| {
        eprintln!("could not open orig/SLUS_207.72: {e}");
        eprintln!("run tools/extract-from-iso.sh first");
        std::process::exit(1);
    });

    // BFS the direct-call graph.
    let mut seen: BTreeSet<u32> = BTreeSet::new();
    let mut queue: VecDeque<(u32, u32)> = VecDeque::new();
    let mut chosen: Vec<u32> = Vec::new();
    queue.push_back((start, 0));
    while let Some((addr, d)) = queue.pop_front() {
        if !seen.insert(addr) || chosen.len() >= limit {
            continue;
        }
        let Some(f) = index().by_address(addr) else {
            continue;
        };
        chosen.push(addr);
        if d >= depth {
            continue;
        }
        for (pc, inst) in program.decode_with_addresses(f) {
            if inst.mnemonic == "jal" {
                if let Operands::Jump { target } = inst.operands {
                    let t = (pc.wrapping_add(4) & 0xF000_0000) | (target << 2);
                    if index().by_address(t).is_some() {
                        queue.push_back((t, d + 1));
                    }
                }
            }
        }
    }

    // Emit.
    let translated: BTreeSet<u32> = chosen.iter().copied().collect();
    let mut src = String::new();
    src.push_str("//! Auto-generated by `recomp-gen`. Do not edit by hand.\n");
    src.push_str("//!\n");
    src.push_str(&format!(
        "//! {} function(s) from the direct-call graph of {start:#010x} (depth {depth}).\n\n",
        chosen.len()
    ));
    src.push_str("#![allow(unused_variables, unused_mut, unused_assignments, clippy::all)]\n\n");
    src.push_str("use crate::Cpu;\n\n");

    let mut total_insts = 0usize;
    let mut unsupported = 0usize;
    for &addr in &chosen {
        let f = index().by_address(addr).unwrap();
        let body = codegen::emit_function(&program, f, &translated);
        total_insts += program.decode(f).len();
        unsupported += body.matches("unimplemented(").count();
        src.push_str(&body);
        src.push('\n');
    }

    // Entry point for the runner: call the start function directly.
    src.push_str(&format!(
        "/// Run the translated entry point ({start:#010x}).\npub fn run_entry(c: &mut Cpu) {{\n    {}(c);\n}}\n",
        codegen::fn_name(start)
    ));

    let path = Path::new(&out);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).ok();
    }
    std::fs::write(path, src).expect("write generated.rs");

    println!("wrote {} function(s) to {}", chosen.len(), out);
    println!("  instructions covered : {total_insts}");
    println!("  unsupported lowering : {unsupported}");
}
