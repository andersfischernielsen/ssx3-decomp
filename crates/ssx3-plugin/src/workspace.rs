//! Building a front end with the Rust code of plugins (`ssx3 plugins build`).
//!
//! Plugin code is not loaded as a library: the plugin folders that declare
//! `[code]` are linked into one generated front end, which calls
//! `ssx3::run` with their `plugin()`s. Adding or removing a code plugin needs
//! this build; data-only plugins do not.

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::discover::{Found, Status};

/// A plugin's Rust package.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Package {
    /// The Cargo package name.
    pub name: String,
    /// The plugin folder (where its `Cargo.toml` is).
    pub dir: PathBuf,
}

impl Package {
    /// The name in Rust code (`ssx3-plugin-hello` is `ssx3_plugin_hello`).
    pub fn ident(&self) -> String {
        self.name.replace('-', "_")
    }
}

/// The plugins with Rust code that a build includes: usable manifests that are
/// not turned off. (Whether the content is ready is a run-time question.)
pub fn packages(found: &[Found]) -> Vec<Package> {
    found
        .iter()
        .filter(|f| !matches!(f.status, Status::Invalid(_) | Status::Disabled))
        .filter_map(|f| {
            let code = f.manifest.as_ref()?.code.as_ref()?;
            Some(Package {
                name: code.package.clone(),
                dir: f.dir.clone(),
            })
        })
        .collect()
}

fn quoted(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

fn slashes(p: &Path) -> String {
    p.display().to_string().replace('\\', "/")
}

/// The generated `Cargo.toml`: a stand-alone workspace whose binary links the
/// engine's front end and the plugin packages.
pub fn manifest_text(repo: &Path, pkgs: &[Package]) -> String {
    let mut s = String::from(
        "# Generated by `ssx3 plugins build`; do not edit.\n\
         [package]\nname = \"ssx3-custom\"\nversion = \"0.1.0\"\nedition = \"2021\"\npublish = false\n\n\
         [[bin]]\nname = \"ssx3-custom\"\npath = \"src/main.rs\"\n\n\
         [[bin]]\nname = \"ssx3-custom-headless\"\npath = \"src/headless.rs\"\n\n[dependencies]\n",
    );
    s += &format!(
        "ssx3 = {{ path = {} }}\n",
        quoted(&slashes(&repo.join("crates/ssx3")))
    );
    s += &format!(
        "ssx3-plugin = {{ path = {} }}\n",
        quoted(&slashes(&repo.join("crates/ssx3-plugin")))
    );
    for p in pkgs {
        s += &format!(
            "{} = {{ path = {} }}\n",
            quoted(&p.name),
            quoted(&slashes(&p.dir))
        );
    }
    s += "\n[workspace]\n\n[profile.release]\nopt-level = 3\nlto = \"thin\"\n\n\
          [profile.game]\ninherits = \"release\"\nlto = false\ncodegen-units = 64\nincremental = true\n";
    s
}

/// The generated `main.rs` (`entry` is `run` or `run_headless`).
pub fn main_text(pkgs: &[Package], entry: &str) -> String {
    let mut s = String::from(
        "// Generated by `ssx3 plugins build`; do not edit.\n\
         fn main() {\n    let plugins: Vec<Box<dyn ssx3_plugin::Plugin>> = vec![\n",
    );
    for p in pkgs {
        s += &format!("        {}::plugin(),\n", p.ident());
    }
    s += &format!("    ];\n    ssx3::{entry}(plugins);\n}}\n");
    s
}

/// Write the generated workspace into `out`.
pub fn generate(found: &[Found], repo: &Path, out: &Path) -> Result<Vec<Package>, String> {
    let pkgs = packages(found);
    let write = |rel: &str, text: String| -> Result<(), String> {
        let path = out.join(rel);
        std::fs::create_dir_all(path.parent().unwrap())
            .and_then(|_| std::fs::write(&path, text))
            .map_err(|e| format!("{}: {e}", path.display()))
    };
    write("Cargo.toml", manifest_text(repo, &pkgs))?;
    write("src/main.rs", main_text(&pkgs, "run"))?;
    write("src/headless.rs", main_text(&pkgs, "run_headless"))?;
    Ok(pkgs)
}

/// Generate and build (`ssx3-custom`, and `ssx3-custom-headless` next to it);
/// the windowed binary, or `None` when no plugin has Rust code.
/// The build shares the engine's `target` folder, so the engine itself is not
/// built twice.
pub fn build(found: &[Found], repo: &Path, out: &Path) -> Result<Option<PathBuf>, String> {
    let pkgs = generate(found, repo, out)?;
    if pkgs.is_empty() {
        return Ok(None);
    }
    println!(
        "building ssx3-custom with: {}",
        pkgs.iter()
            .map(|p| p.name.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    );
    let target = repo.join("target");
    let status = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .args(["build", "--profile", "game", "--manifest-path"])
        .arg(out.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", &target)
        .status()
        .map_err(|e| format!("cannot run cargo: {e}"))?;
    if !status.success() {
        return Err(format!("cargo build failed ({status})"));
    }
    let exe = if cfg!(windows) {
        "ssx3-custom.exe"
    } else {
        "ssx3-custom"
    };
    Ok(Some(target.join("game").join(exe)))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::discover::{discover, testutil::Tmp, Filter, Roots};

    fn found(t: &Tmp) -> Vec<Found> {
        for (id, code) in [
            ("alpha", Some("ssx3-plugin-alpha")),
            ("data", None),
            ("zed", Some("zed-code")),
        ] {
            let d = t.path().join("plugins").join(id);
            std::fs::create_dir_all(d.join("content")).unwrap();
            let code = code
                .map(|p| format!("[code]\npackage = \"{p}\"\n"))
                .unwrap_or_default();
            std::fs::write(
                d.join("plugin.toml"),
                format!("[plugin]\nid = \"{id}\"\napi = \"0.1\"\n{code}"),
            )
            .unwrap();
        }
        discover(
            &Roots {
                plugin_dirs: vec![t.path().join("plugins")],
                disc_dirs: vec![],
                cache: t.path().join("cache"),
            },
            &Filter::All,
        )
    }

    #[test]
    fn only_plugins_with_rust_code_are_built_in() {
        let t = Tmp::new("ws");
        let pkgs = packages(&found(&t));
        assert_eq!(
            pkgs.iter().map(|p| p.name.as_str()).collect::<Vec<_>>(),
            ["ssx3-plugin-alpha", "zed-code"]
        );
        assert_eq!(pkgs[0].ident(), "ssx3_plugin_alpha");
    }

    #[test]
    fn the_generated_workspace_names_the_engine_and_each_plugin() {
        let t = Tmp::new("wsgen");
        let repo = Path::new("/the/repo");
        let out = t.path().join("out");
        let pkgs = generate(&found(&t), repo, &out).unwrap();
        assert_eq!(pkgs.len(), 2);
        let manifest: toml::Value =
            toml::from_str(&std::fs::read_to_string(out.join("Cargo.toml")).unwrap()).unwrap();
        let deps = manifest["dependencies"].as_table().unwrap();
        assert_eq!(deps["ssx3"]["path"].as_str(), Some("/the/repo/crates/ssx3"));
        assert!(deps.contains_key("ssx3-plugin"));
        assert!(deps["ssx3-plugin-alpha"]["path"]
            .as_str()
            .unwrap()
            .ends_with("plugins/alpha"));
        assert!(
            manifest.get("workspace").is_some(),
            "stand-alone, not a member of another workspace"
        );
        let main = std::fs::read_to_string(out.join("src/main.rs")).unwrap();
        assert!(main.contains("ssx3_plugin_alpha::plugin(),"), "{main}");
        assert!(main.contains("zed_code::plugin(),"), "{main}");
        assert!(main.contains("ssx3::run(plugins);"), "{main}");
        let headless = std::fs::read_to_string(out.join("src/headless.rs")).unwrap();
        assert!(
            headless.contains("ssx3::run_headless(plugins);"),
            "{headless}"
        );
    }

    #[test]
    fn nothing_to_build_without_rust_code() {
        let t = Tmp::new("wsnone");
        let d = t.path().join("plugins/data");
        std::fs::create_dir_all(d.join("content")).unwrap();
        std::fs::write(
            d.join("plugin.toml"),
            "[plugin]\nid = \"data\"\napi = \"0.1\"\n",
        )
        .unwrap();
        let f = discover(
            &Roots {
                plugin_dirs: vec![t.path().join("plugins")],
                disc_dirs: vec![],
                cache: t.path().join("cache"),
            },
            &Filter::All,
        );
        assert_eq!(build(&f, Path::new("/x"), &t.path().join("out")), Ok(None));
    }
}
